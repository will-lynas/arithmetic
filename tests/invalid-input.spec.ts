import { expect, test, type Page } from '@playwright/test'

const snapshot = (page: Page) => page.evaluate(() => Object.fromEntries(Object.keys(localStorage).sort().map(k => [k, localStorage.getItem(k)])))
const pageErrors = new WeakMap<Page,string[]>()
test.beforeEach(({page}) => { const errors:string[]=[]; pageErrors.set(page,errors); page.on('pageerror',error=>errors.push(error.stack ?? error.message)) })
test.afterEach(({page}) => { expect(pageErrors.get(page)).toEqual([]) })

test('malformed multiplication is a refusal, not a wrong answer', async ({page}) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.stack ?? error.message))
  await page.goto('/multiplication')
  await page.getByRole('button', {name:'Start', exact:true}).click()
  const input = page.getByRole('textbox', {name:'Answer', exact:true})
  await expect(input).toBeFocused()
  const question = await page.getByTestId('question').innerText()
  const before = await snapshot(page)
  await input.fill('6]'); await input.press('Enter')
  await expect(page.getByRole('status')).toHaveText('Enter a whole number')
  expect(await snapshot(page)).toEqual(before)
  await expect(page.getByTestId('question')).toHaveText(question)
  await page.screenshot({path:'artifacts/malformed-multiplication.png'})
  await expect(page.locator('.equation[data-invalid="true"]')).toHaveCount(0)
  await expect(input).toHaveAttribute('data-wrong','false')
  expect(errors).toEqual([])
})

test('malformed division focuses only the invalid field without grading either field', async ({page}) => {
  await page.goto('/division')
  const main = page.getByRole('main', {name:'Division', exact:true})
  await main.getByRole('button', {name:'Start', exact:true}).click()
  const q = page.getByRole('textbox', {name:'Quotient', exact:true})
  const r = page.getByRole('textbox', {name:'Remainder', exact:true})
  await expect(q).toBeFocused()
  const plan = await page.evaluate(() => Object.keys(localStorage).filter(k => k.startsWith('arithmetic:division:event:v1:')).map(k => JSON.parse(localStorage.getItem(k)!)).find(e => e.kind === 'start').questions[0])
  await q.fill(String(plan.quotient)); await r.fill('6]')
  const before = await snapshot(page)
  await r.press('Enter')
  expect(await snapshot(page)).toEqual(before)
  await expect(r).toBeFocused()
  await page.screenshot({path:'artifacts/malformed-division.png'})
  await expect(main.locator('.equation')).toHaveAttribute('data-invalid','false')
  await expect(q).toHaveAttribute('aria-invalid','false')
  await expect(r).toHaveAttribute('data-malformed','true')
  await expect(q).toHaveAttribute('data-wrong','false')
  await expect(r).toHaveAttribute('data-wrong','false')
  await expect(main.getByRole('status')).toHaveText('Enter two whole numbers')
})

test.describe('phone validation', () => {
  test.use({viewport:{width:375,height:667},isMobile:true,hasTouch:true})
  for (const mode of ['multiplication','division']) for (const theme of ['dark','light']) for (const reduced of [false,true]) {
    test(`${mode} ${theme} ${reduced?'reduced':'full'} motion refuses syntax and preserves first try`, async ({page}) => {
      await page.emulateMedia({reducedMotion:reduced?'reduce':'no-preference'})
      await page.addInitScript(theme => {
        localStorage.setItem('arithmetic:theme',theme)
        Object.assign(window,{testNow:0,animations:[]})
        performance.now=()=> (window as any).testNow
        Object.defineProperty(document,'hasFocus',{value:()=>true})
        document.addEventListener('animationstart',e=>(window as any).animations.push(e.animationName))
      },theme)
      await page.goto('/'+mode)
      const main=mode==='division'?page.getByRole('main',{name:'Division',exact:true}):page.locator('.practice-page')
      await main.getByRole('button',{name:'Start',exact:true}).tap()
      const first=main.getByRole('textbox',{name:mode==='division'?'Quotient':'Answer',exact:true})
      const remainder=main.getByRole('textbox',{name:'Remainder',exact:true})
      await expect(first).toBeFocused()
      await first.evaluate(e=>{(e as any).identity='same-input'})
      const question=main.getByTestId(mode==='division'?'division-question':'question')
      const text=await question.innerText()
      const plan=mode==='division'?await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('arithmetic:division:event:v1:')).map(k=>JSON.parse(localStorage.getItem(k)!)).find(e=>e.kind==='start').questions):null
      const answer=plan?plan[0].quotient:text.split('×').map(Number).reduce((a,b)=>a*b)
      if(plan)await remainder.fill(String(plan[0].remainder))
      const before=await snapshot(page)
      await page.evaluate(()=>{(window as any).testNow=1200})
      for(const [index,bad] of ['6]','letters','','1.2','9007199254740992'].entries()) {
        await first.fill(bad)
        if(index%2)await main.getByRole('button',{name:'Submit',exact:true}).tap()
        else await first.press('Enter')
        await expect(main.getByRole('status')).toHaveText(plan?'Enter two whole numbers':'Enter a whole number')
        await expect(first).toBeFocused(); await expect(first).toHaveValue(bad)
        await expect(first).toHaveAttribute('aria-invalid','true')
        await expect(main.locator('[data-wrong="true"]')).toHaveCount(0)
        await expect(main.locator('.equation')).toHaveAttribute('data-invalid','false')
        await expect(question).toHaveText(text)
        expect(await snapshot(page)).toEqual(before)
        expect(await first.evaluate(e=>(e as any).identity)).toBe('same-input')
        const colors=await first.evaluate(e=>({color:getComputedStyle(e).color,text:getComputedStyle(e.closest('.app')!).color,border:getComputedStyle(e).borderBottomStyle}))
        expect(colors.border).toBe('dashed')
        expect(colors.color).toBe(colors.text)
        if(reduced)expect(await main.locator('.equation').evaluate(e=>getComputedStyle(e).animationName)).toBe('none')
        else await expect(main.locator('.equation')).not.toHaveAttribute('data-refusal',/./)
      }
      if(plan) {
        await first.fill(String(answer)); await remainder.fill('6]'); await main.getByRole('button',{name:'Submit',exact:true}).tap()
        await expect(remainder).toBeFocused();await expect(first).toHaveAttribute('aria-invalid','false')
        await expect(remainder).toHaveAttribute('data-malformed','true')
        expect(await snapshot(page)).toEqual(before)
      }
      await page.screenshot({path:`artifacts/refusal-${mode}-${theme}-${reduced?'reduced':'motion'}.png`})
      const invalidField=plan?remainder:first
      const animationCount=await page.evaluate(()=>(window as any).animations.length)
      await invalidField.press('Enter')
      if(!reduced) {
        await expect.poll(()=>page.evaluate(()=>(window as any).animations.length)).toBeGreaterThan(animationCount)
        await expect(main.locator('.equation')).not.toHaveAttribute('data-refusal',/./)
      }
      await first.fill(String(answer));if(plan)await remainder.fill(String(plan[0].remainder))
      await page.evaluate(()=>{(window as any).testNow=3400})
      await main.getByRole('button',{name:'Submit',exact:true}).tap()
      await expect(main.getByLabel('Question progress')).toHaveText(plan?'2 / 5':'2 / 10')
      const saved=await snapshot(page)
      for(const [k,v]of Object.entries(before))expect(saved[k]).toBe(v)
      const attempts=Object.entries(saved).filter(([k])=>k.startsWith(plan?'arithmetic:division:event:v1:':'arithmetic:attempt:v1:')).map(([,v])=>JSON.parse(v!)).filter(e=>!plan || e.kind==='attempt')
      expect(attempts).toHaveLength(1);expect(attempts[0].correct).toBe(true);expect(attempts[0].elapsedMs).toBe(3400)
      await expect(main.locator('[data-malformed="true"], [data-wrong="true"], [data-refusal]')).toHaveCount(0)
      if(!plan) {
        await page.getByRole('link',{name:'Stats',exact:true}).tap()
        await expect(page.getByRole('table',{name:'First-try accuracy by ordered multiplication pair',exact:true}).locator(`[data-pair="${attempts[0].left}x${attempts[0].right}"]`)).toHaveText('100%')
        await page.getByRole('link',{name:'Practice',exact:true}).tap()
      }
      await first.fill('-1');if(plan)await remainder.fill(String(plan[1].remainder))
      await first.evaluate(e=>{e.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}));e.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}))})
      await expect(main.getByRole('status')).toHaveText('Incorrect — try again')
      await expect(first).toHaveAttribute('data-wrong','true')
      await expect(first).toBeFocused()
      expect(await first.evaluate((e:HTMLInputElement)=>[e.selectionStart,e.selectionEnd])).toEqual([0,2])
      const wrong=await snapshot(page)
      expect(Object.keys(wrong).length).toBe(Object.keys(saved).length+1)
      for(const [k,v]of Object.entries(saved))expect(wrong[k]).toBe(v)
      const correct=plan?plan[1].quotient:(await question.innerText()).split('×').map(Number).reduce((a,b)=>a*b)
      await first.fill(String(correct));await first.press('Enter')
      await expect(main.getByLabel('Question progress')).toHaveText(plan?'3 / 5':'3 / 10')
      const corrected=await snapshot(page)
      for(const [k,v]of Object.entries(wrong))expect(corrected[k]).toBe(v)
      await first.fill('6]');await first.press('Enter')
      await first.press('Escape')
      await expect(main.getByRole('button',{name:'Start',exact:true})).toBeVisible()
      await main.getByRole('button',{name:'Start',exact:true}).tap()
      await expect(first).toBeFocused();await expect(first).toHaveValue('')
      await expect(main.locator('[data-malformed="true"], [data-wrong="true"], [data-refusal]')).toHaveCount(0)
    })
  }
})
