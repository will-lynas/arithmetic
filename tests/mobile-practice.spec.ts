import { expect, test, type Page } from '@playwright/test'

test.use({ viewport: { width: 390, height: 740 }, isMobile: true, hasTouch: true })
async function records(page: Page) {
  return page.evaluate(() => Object.keys(localStorage).filter(k => k.startsWith('arithmetic:attempt:v1:')).map(k => JSON.parse(localStorage.getItem(k)!)))
}
async function solution(page: Page) {
  const [a,b] = (await page.getByTestId('question').innerText()).match(/\d+/g)!.map(Number)
  return String(a*b)
}
async function touchTarget(page: Page, name: string) {
  const box = await page.getByRole('button',{name,exact:true}).boundingBox()
  expect(box).not.toBeNull()
  expect(box!.width).toBeGreaterThanOrEqual(44)
  expect(box!.height).toBeGreaterThanOrEqual(44)
}
test('Start focuses an editable input inside the tap, but cannot submit before ownership', async ({page}) => {
  await page.goto('/')
  await expect(page.getByRole('button',{name:'Start',exact:true})).toBeEnabled()
  await page.evaluate(() => {
    const w=window as any
    const request=navigator.locks.request.bind(navigator.locks)
    navigator.locks.request=((...args: any[]) => new Promise(resolve => { w.releaseClaim=()=>resolve((request as any)(...args)) })) as any
    w.focusLog=[]; w.inClick=false
    document.addEventListener('click',()=>{w.inClick=true},true)
    document.addEventListener('click',()=>{w.inClick=false})
    document.addEventListener('focusin',event=>{
      if(['Answer','Starting round'].includes((event.target as HTMLElement).getAttribute('aria-label')!)) w.focusLog.push({inClick:w.inClick,readOnly:(event.target as HTMLInputElement).readOnly})
    })
  })
  await page.getByRole('button',{name:'Start',exact:true}).tap()
  const input=page.getByRole('textbox',{name:'Answer'})
  expect(await page.evaluate(()=>(window as any).focusLog)).toEqual([{inClick:true,readOnly:false}])
  await expect(page.getByRole('button',{name:'Submit',exact:true})).toBeDisabled()
  await expect(page.getByRole('textbox',{name:'Answer',exact:true})).toHaveCount(0)
  const starting=page.getByRole('textbox',{name:'Starting round',exact:true})
  await expect(starting).toBeFocused()
  await page.keyboard.insertText('144')
  await starting.press('Enter')
  expect(await records(page)).toHaveLength(0)
  await page.evaluate(() => { (window as any).releaseClaim() })
  await expect(page.getByRole('button',{name:'Submit',exact:true})).toBeEnabled()
  await expect(input).toBeFocused()
  await expect(input).toHaveValue('')
})
test('touch-only round corrects wrong answers, preserves focus and restarts', async ({page}) => {
  await page.goto('/')
  await page.getByRole('button',{name:'Start',exact:true}).tap()
  const input = page.getByRole('textbox',{name:'Answer'})
  const submit = page.getByRole('button',{name:'Submit',exact:true})
  await expect(input).toBeFocused()
  await expect(input).toHaveAttribute('inputmode','numeric')
  await expect(input).toHaveAttribute('enterkeyhint','done')
  await submit.tap(); await input.fill('2.5'); await submit.tap()
  expect(await records(page)).toHaveLength(0)
  await input.fill('0'); await submit.tap()
  await expect(input).toBeFocused()
  expect(await input.evaluate((e: HTMLInputElement) => [e.selectionStart,e.selectionEnd])).toEqual([0,1])
  for(let i=0;i<10;i++) {
    await input.fill(await solution(page)); await submit.tap()
    if(i<9) { await expect(input).toBeFocused(); await expect(input).toHaveValue('') }
  }
  await expect(page.getByRole('heading',{name:'Round complete'})).toBeVisible()
  expect(await records(page)).toHaveLength(11)
  await touchTarget(page,'New round')
  await page.getByRole('button',{name:'New round'}).tap()
  await expect(input).toBeFocused()
  await page.getByRole('button',{name:'Cancel',exact:true}).tap()
  await expect(page.getByRole('button',{name:'Start',exact:true})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button',{name:'Start',exact:true})).toBeVisible()
  expect(await records(page)).toHaveLength(11)
})
test('rapid taps, held pointers and synthetic clicks cannot duplicate or submit a stale answer', async ({page}) => {
  await page.goto('/'); await page.getByRole('button',{name:'Start',exact:true}).tap()
  const input=page.getByRole('textbox',{name:'Answer'})
  const submit=page.getByRole('button',{name:'Submit',exact:true})
  await input.fill(await solution(page))
  await input.evaluate(e => { (window as any).originalInput=e; (window as any).blurs=0; e.addEventListener('blur',()=>{(window as any).blurs++}) })
  await submit.dispatchEvent('pointerdown',{pointerType:'touch',isPrimary:true})
  expect(await records(page)).toHaveLength(0)
  await submit.tap(); await submit.tap()
  await expect(page.getByText('2 / 10',{exact:true})).toBeVisible()
  expect(await records(page)).toHaveLength(1)
  expect(await input.evaluate(e=>e===(window as any).originalInput)).toBe(true)
  expect(await page.evaluate(()=>(window as any).blurs)).toBe(0)
  await input.fill('0')
  await submit.evaluate(e=>{for(let i=0;i<5;i++) (e as HTMLButtonElement).click()})
  expect(await records(page)).toHaveLength(2)
  await expect(input).toBeFocused()
  await expect(page.getByText('2 / 10',{exact:true})).toBeVisible()
})
test('touch Retry saving keeps exact pending bytes and blocks Cancel until durable', async ({page}) => {
  await page.goto('/'); await page.getByRole('button',{name:'Start',exact:true}).tap()
  const input=page.getByRole('textbox',{name:'Answer'})
  await input.fill(await solution(page))
  await page.evaluate(()=>{
    const w=window as any; w.originalSet=Storage.prototype.setItem; w.writes=[]
    Storage.prototype.setItem=function(k,v){w.writes.push([k,v]); throw new DOMException('Full','QuotaExceededError')}
  })
  await page.getByRole('button',{name:'Submit',exact:true}).tap()
  await expect(input).toBeDisabled()
  await expect(page.getByRole('button',{name:'Submit',exact:true})).toBeDisabled()
  const cancel=page.getByRole('button',{name:'Cancel',exact:true})
  await expect(cancel).toBeDisabled(); await cancel.evaluate(e=>(e as HTMLButtonElement).click())
  expect(await records(page)).toHaveLength(0)
  await touchTarget(page,'Retry saving')
  await page.screenshot({path:'artifacts/mobile-save-error.png'})
  const attempted=await page.evaluate(()=>(window as any).writes[0])
  await page.evaluate(()=>{Storage.prototype.setItem=(window as any).originalSet})
  await page.getByRole('button',{name:'Retry saving'}).tap()
  expect(await page.evaluate(k=>localStorage.getItem(k),attempted[0])).toBe(attempted[1])
  await expect(page.getByText('2 / 10',{exact:true})).toBeVisible()
  await expect(input).toBeFocused()
  await cancel.tap()
  await page.reload(); await expect(page.getByRole('button',{name:'Start',exact:true})).toBeVisible()
  expect(await page.evaluate(k=>localStorage.getItem(k),attempted[0])).toBe(attempted[1])
})
test('touch navigation preserves answer and progress; failed cancellation remains retryable by tap', async ({page}) => {
  await page.goto('/'); await page.getByRole('button',{name:'Start',exact:true}).tap()
  const input=page.getByRole('textbox',{name:'Answer'})
  await expect(input).toBeFocused()
  await input.fill('0'); await page.getByRole('button',{name:'Submit',exact:true}).tap()
  const before=await records(page)
  await input.fill(await solution(page))
  const text=await input.inputValue(); const question=await page.getByTestId('question').innerText()
  await page.getByRole('link',{name:'Stats',exact:true}).tap()
  await expect(page.getByRole('button',{name:'Cancel',exact:true})).toHaveCount(0)
  await page.waitForTimeout(500); await page.keyboard.press('Enter'); await page.keyboard.press('Escape')
  await page.getByRole('link',{name:'Practice',exact:true}).tap()
  await expect(input).toHaveValue(text); await expect(input).toBeFocused()
  await expect(page.getByTestId('question')).toHaveText(question)
  expect(await records(page)).toEqual(before)
  await page.evaluate(()=>{(window as any).originalSet=Storage.prototype.setItem; Storage.prototype.setItem=()=>{throw new DOMException('Full','QuotaExceededError')}})
  await page.getByRole('button',{name:'Cancel',exact:true}).tap()
  await expect(page.getByRole('alert')).toContainText('try canceling again')
  await expect(input).toHaveValue(text)
  await page.evaluate(()=>{Storage.prototype.setItem=(window as any).originalSet})
  await page.getByRole('button',{name:'Cancel',exact:true}).tap()
  await page.reload(); await expect(page.getByRole('button',{name:'Start',exact:true})).toBeVisible()
  expect(await records(page)).toEqual(before)
})
for(const theme of ['dark','light']) test(`${theme}: largest operands, error and touch targets fit narrow and keyboard-height viewports`, async ({page}) => {
  await page.goto('/')
  await page.evaluate(theme => {
    localStorage.setItem('arithmetic:theme',theme)
    const id=crypto.randomUUID()
    localStorage.setItem('arithmetic:attempt:v1:'+id, JSON.stringify({version:1,id,roundId:crypto.randomUUID(),questionIndex:0,left:12,right:12,answer:0,correct:false,elapsedMs:1000,submittedAt:'2026-01-01T00:00:00.000Z'}))
  },theme)
  await page.reload()
  const input=page.getByRole('textbox',{name:'Answer'})
  await expect(input).toBeFocused()
  await input.fill('144')
  for(const [width,height] of [[320,568],[375,667],[390,740],[430,932],[667,320],[390,320]]) {
    await page.setViewportSize({width,height})
    await touchTarget(page,'Submit'); await touchTarget(page,'Cancel')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const equation=await page.locator('.equation').boundingBox()
    expect(equation!.x).toBeGreaterThanOrEqual(0)
    expect(equation!.x+equation!.width).toBeLessThanOrEqual(width)
    const submit=await page.getByRole('button',{name:'Submit',exact:true}).boundingBox()
    expect(submit!.y+submit!.height).toBeLessThanOrEqual(height)
    expect(await input.evaluate(e=>parseFloat(getComputedStyle(e).fontSize))).toBeGreaterThanOrEqual(16)
    await page.screenshot({path:`artifacts/mobile-${theme}-${width}x${height}.png`})
  }
  await page.emulateMedia({reducedMotion:'reduce'})
  await input.fill('0'); await page.getByRole('button',{name:'Submit',exact:true}).tap()
  await expect(input).toHaveAttribute('aria-invalid','true')
  expect(await page.locator('.equation').evaluate(e=>getComputedStyle(e).animationName)).toBe('none')
  await page.screenshot({path:`artifacts/mobile-${theme}-error.png`})
  await page.getByRole('button',{name:'Cancel',exact:true}).tap()
  await touchTarget(page,'Start')
})
