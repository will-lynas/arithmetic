import { expect, test, type Page } from '@playwright/test'
async function answer(page: Page) {
  const text = await page.getByTestId('question').innerText()
  const [left, right] = text.match(/\d+/g)!.map(Number)
  return left * right
}
async function records(page: Page) {
  return page.evaluate(() => Object.keys(localStorage).filter(k => k.startsWith('arithmetic:attempt:v1:')).flatMap(k => { try { return [JSON.parse(localStorage.getItem(k)!)] } catch { return [] } }))
}
test('ten questions require correction, save every valid submission, and restart on Enter', async ({page}) => {
  await page.goto('/')
  await expect(page.getByRole('button', {name: 'Start', exact: true})).toBeVisible()
  await page.keyboard.press('Enter')
  const input = page.getByRole('textbox', {name: 'Answer'})
  await expect(input).toBeFocused()
  await input.fill('0'); await input.press('Enter')
  await expect(page.getByText('1 / 10', {exact:true})).toBeVisible()
  await expect(input).toHaveAttribute('aria-invalid','true')
  expect(await input.evaluate((e: HTMLInputElement) => [e.selectionStart,e.selectionEnd])).toEqual([0,1])
  for (let i = 0; i < 10; i++) {
    await input.fill(String(await answer(page))); await input.press('Enter')
  }
  await expect(page.getByRole('heading', {name:'Round complete'})).toBeVisible()
  const saved = await records(page)
  expect(saved).toHaveLength(11)
  expect(saved.filter(r => r.correct)).toHaveLength(10)
  expect(saved.filter(r => r.questionIndex === 0)).toHaveLength(2)
  await page.reload(); await expect(page.getByRole('heading', {name:'Round complete'})).toBeVisible()
  await page.keyboard.press('Enter'); await expect(input).toBeFocused()
  await expect(page.getByText('1 / 10', {exact:true})).toBeVisible()
  expect(await page.getByRole('combobox').count()).toBe(0)
  await expect(page.getByRole('link', {name: /settings/i})).toHaveCount(0)
})
test('invalid, blank, Tab, space, IME, repeat and rapid Enter cannot create duplicate attempts', async ({page}) => {
  await page.goto('/'); await page.keyboard.press('Enter')
  const input = page.getByRole('textbox', {name:'Answer'})
  await input.press('Enter'); await input.fill('2.5'); await input.press('Enter')
  expect(await records(page)).toHaveLength(0)
  await input.fill(String(await answer(page)))
  await input.press('Space'); await input.press('Tab')
  expect(await records(page)).toHaveLength(0)
  await input.focus()
  await input.evaluate(e => {
    e.dispatchEvent(new KeyboardEvent('keydown', {key:'Enter', repeat:true, bubbles:true}))
    e.dispatchEvent(new KeyboardEvent('keydown', {key:'Enter', isComposing:true, bubbles:true}))
    e.dispatchEvent(new KeyboardEvent('keydown', {key:'Enter', keyCode:229, bubbles:true}))
  })
  expect(await records(page)).toHaveLength(0)
  await input.fill(String(await answer(page)))
  await input.evaluate(e => { for(let i=0;i<5;i++) e.dispatchEvent(new KeyboardEvent('keydown', {key:'Enter', bubbles:true, cancelable:true})) })
  expect(await records(page)).toHaveLength(1)
  await expect(page.getByText('2 / 10', {exact:true})).toBeVisible()
})
test('failed storage retains exact pending attempt, does not advance, and retries durably', async ({page}) => {
  await page.goto('/'); await page.keyboard.press('Enter')
  const input = page.getByRole('textbox', {name:'Answer'})
  await input.fill(String(await answer(page)))
  await page.evaluate(() => { (window as any).originalSet = Storage.prototype.setItem; Storage.prototype.setItem = () => { throw new DOMException('Full','QuotaExceededError') } })
  await input.press('Enter')
  await expect(page.getByRole('button', {name:'Retry saving'})).toBeVisible()
  await expect(page.getByText('1 / 10', {exact:true})).toBeVisible()
  await expect(input).toBeDisabled(); expect(await records(page)).toHaveLength(0)
  await page.evaluate(() => { Storage.prototype.setItem = (window as any).originalSet })
  await page.getByRole('button', {name:'Retry saving'}).click()
  await expect(page.getByText('2 / 10', {exact:true})).toBeVisible()
  expect(await records(page)).toHaveLength(1)
})
test('corrupt and future data are preserved with warning, other applications remain untouched', async ({page}) => {
  await page.goto('/')
  const data = {'arithmetic:attempt:v1:broken':'{', 'arithmetic:attempt:v9:newer':'{"version":9}', 'times-tables:scores':'private-preservation-fixture'}
  await page.evaluate(data => { for (const [k,v] of Object.entries(data)) localStorage.setItem(k,v) },data)
  await page.reload(); await expect(page.getByRole('alert')).toContainText('original data has been kept')
  await page.keyboard.press('Enter'); const input = page.getByRole('textbox', {name:'Answer'})
  await input.fill('0'); await input.press('Enter'); await page.reload()
  expect(await page.evaluate(keys => Object.fromEntries(keys.map(k => [k,localStorage.getItem(k)])),Object.keys(data))).toEqual(data)
  await expect(page.getByText('1 / 10', {exact:true})).toBeVisible()
  expect(await records(page).then(rs => rs.filter(r => r && r.version === 1))).toHaveLength(1)
})
test('independent tabs append without overwriting events', async ({page, context}) => {
  await page.goto('/'); const second = await context.newPage(); await second.goto('/')
  for(const tab of [page, second]) {
    await tab.bringToFront(); await tab.getByRole('button', {name:'Start',exact:true}).click()
    await tab.getByRole('textbox', {name:'Answer'}).fill('0'); await tab.keyboard.press('Enter')
  }
  expect(await records(page)).toHaveLength(2)
  expect(new Set((await records(page)).map(r => r.id)).size).toBe(2)
  await page.reload(); expect(await records(page)).toHaveLength(2)
})
test('active time excludes ready and blur, increases across retries', async ({page}) => {
  await page.goto('/'); await page.waitForTimeout(250); await page.keyboard.press('Enter')
  const input = page.getByRole('textbox', {name:'Answer'})
  await page.waitForTimeout(100); await input.fill('0'); await input.press('Enter')
  const first = (await records(page))[0]
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  // Override focus predicate so the synthetic blur exercises the real pause boundary.
  await page.evaluate(() => { Object.defineProperty(document,'hasFocus',{configurable:true,value:()=>false}); window.dispatchEvent(new Event('blur')) })
  await page.waitForTimeout(500)
  await page.evaluate(() => { Object.defineProperty(document,'hasFocus',{configurable:true,value:()=>true}); window.dispatchEvent(new Event('focus')) })
  await page.waitForTimeout(100); await input.fill(String(await answer(page))); await input.press('Enter')
  const second = (await records(page)).find(r => r.correct)
  expect(second.elapsedMs).toBeGreaterThan(first.elapsedMs)
  expect(second.elapsedMs - first.elapsedMs).toBeLessThan(450)
})
