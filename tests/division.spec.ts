import { expect, test, type Page } from '@playwright/test'
const errors = new WeakMap<Page,string[]>()
test.beforeEach(({page})=>{const found:string[]=[];errors.set(page,found);page.on('pageerror',e=>found.push(e.message));page.on('console',e=>{if(e.type()==='error')found.push(e.text())})})
test.afterEach(({page})=>{expect(errors.get(page)).toEqual([])})
const division = (page:Page) => page.getByRole('main', {name:'Division'})
async function start(page:Page) {
  await page.goto('/division')
  await division(page).getByRole('button',{name:'Start',exact:true}).click()
  await expect(page.getByRole('textbox',{name:'Quotient',exact:true})).toBeFocused()
}
async function solution(page:Page) {
  const [dividend,divisor] = (await page.getByTestId('division-question').innerText()).match(/\d+/g)!.map(Number)
  return [Math.floor(dividend/divisor),dividend%divisor]
}
async function entries(page:Page) {
  return page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('arithmetic:division:event:v1:')).map(k=>JSON.parse(localStorage.getItem(k)!)))
}
