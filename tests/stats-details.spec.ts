import { expect, test } from '@playwright/test'

const cell = (page: import('@playwright/test').Page, pair: string) => page.locator(`[data-pair="${pair}"]`)

test('calculation details start empty without placeholder text', async ({ page }) => {
  await page.goto('/stats')
  await expect(page.locator('.stats-cell')).toHaveCount(144)
  await expect(page.locator('.stats-detail')).toHaveText('')
  await expect(page.getByRole('region', { name: /× .*details/ })).toHaveCount(0)
})

test('hover follows cells and clears over headers, gaps and outside even after clicking', async ({ page }) => {
  await page.goto('/stats')
  const detail = page.locator('.stats-detail')
  const a = cell(page, '9x6')
  const b = cell(page, '6x9')
  await a.hover()
  await expect(detail).toHaveAttribute('aria-label', '9 × 6 details')
  await b.hover()
  await expect(detail).toHaveAttribute('aria-label', '6 × 9 details')
  await page.locator('.stats-heatmap thead th').first().hover()
  await expect(detail).toHaveText('')
  await a.hover()
  const bounds = (await a.boundingBox())!
  await page.mouse.move(bounds.x - 2, bounds.y + bounds.height / 2)
  await expect(detail).toHaveText('')
  await a.hover()
  await page.mouse.move(1, 1)
  await expect(detail).toHaveText('')
  await a.click()
  await expect(detail).toHaveAttribute('aria-label', '9 × 6 details')
  await page.mouse.move(1, 1)
  await expect(a).toBeFocused()
  await expect(detail).toHaveText('')
})

test('keyboard Tab and arrows reveal focused details and blur clears them', async ({ page }) => {
  await page.goto('/stats')
  const detail = page.locator('.stats-detail')
  await page.getByRole('region', { name: 'Multiplication accuracy map', exact: true }).focus()
  await page.keyboard.press('Tab')
  await expect(cell(page, '1x1')).toBeFocused()
  await expect(detail).toHaveAttribute('aria-label', '1 × 1 details')
  await page.keyboard.press('ArrowRight')
  await expect(cell(page, '1x2')).toBeFocused()
  await expect(detail).toHaveAttribute('aria-label', '1 × 2 details')
  await page.keyboard.press('ArrowDown')
  await expect(detail).toHaveAttribute('aria-label', '2 × 2 details')
  await cell(page, '9x6').hover()
  await expect(detail).toHaveAttribute('aria-label', '9 × 6 details')
  await page.mouse.move(1, 1)
  await expect(detail).toHaveAttribute('aria-label', '2 × 2 details')
  await page.keyboard.press('Shift+Tab')
  await expect(detail).toHaveText('')
  await cell(page, '9x6').click()
  await page.mouse.move(1, 1)
  await expect(detail).toHaveText('')
  await page.keyboard.press('ArrowRight')
  await expect(detail).toHaveAttribute('aria-label', '9 × 7 details')
  await page.keyboard.press('Tab')
  await expect(detail).toHaveText('')
})

test('route remount and reload do not retain previous detail selection', async ({ page }) => {
  await page.goto('/stats')
  await cell(page, '9x6').click()
  await page.getByRole('link', { name: 'Practice', exact: true }).click()
  await page.getByRole('link', { name: 'Stats', exact: true }).click()
  await expect(page.locator('.stats-detail')).toHaveText('')
  await cell(page, '6x9').hover()
  await page.mouse.move(1, 1)
  await page.reload()
  await expect(page.locator('.stats-detail')).toHaveText('')
})

test('touch release does not leave sticky details', async ({ browser, baseURL }) => {
  const context = await browser.newContext({ baseURL, hasTouch: true, isMobile: true, viewport: { width: 375, height: 812 } })
  const page = await context.newPage()
  await page.goto('/stats')
  await cell(page, '9x6').tap()
  await expect(page.locator('.stats-detail')).toHaveText('')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await context.close()
})

for (const theme of ['dark', 'light']) for (const width of [1440, 375]) {
  test(`details preserve layout and data in ${theme} at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto('/stats')
    await page.evaluate(theme => {
      localStorage.setItem('arithmetic:theme', theme)
      const id = crypto.randomUUID()
      localStorage.setItem('arithmetic:attempt:v1:' + id, JSON.stringify({ version: 1, id, roundId: crypto.randomUUID(), questionIndex: 0, left: 9, right: 6, answer: 54, correct: true, elapsedMs: 3000, submittedAt: '2026-01-01T00:00:00.000Z' }))
    }, theme)
    await page.reload()
    const detail = page.locator('.stats-detail')
    await expect(detail).toHaveText('')
    await cell(page, '9x6').scrollIntoViewIfNeeded()
    const before = await page.locator('.stats-heatmap').boundingBox()
    const emptyHeight = await detail.evaluate(element => element.getBoundingClientRect().height)
    await page.screenshot({ path: `artifacts/stats-details-${theme}-${width}-empty.png`, fullPage: true })
    await cell(page, '9x6').hover()
    await expect(detail).toHaveAttribute('aria-label', '9 × 6 details')
    await expect(detail).toContainText('1 / 1 (100%)')
    await expect(detail).toContainText('3.00 s')
    expect(await page.locator('.stats-heatmap').boundingBox()).toEqual(before)
    expect(await detail.evaluate(element => element.getBoundingClientRect().height)).toBe(emptyHeight)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `artifacts/stats-details-${theme}-${width}-hover.png`, fullPage: true })
    await page.mouse.move(1, 1)
    await expect(detail).toHaveText('')
    await page.screenshot({ path: `artifacts/stats-details-${theme}-${width}-cleared.png`, fullPage: true })
  })
}
