import { expect, test, type Page } from '@playwright/test'
import type { AttemptRecord } from '../src/types'
const roundId = '30e91bd6-fb88-4645-8c76-22b03751f8b0'
function fixture(overrides: Partial<AttemptRecord> = {}): AttemptRecord { return {version:1,id:crypto.randomUUID(),roundId,questionIndex:0,left:9,right:6,answer:53,correct:false,elapsedMs:1000,submittedAt:'2026-01-01T00:00:00.000Z',...overrides} }
async function seed(page: Page, attempts: AttemptRecord[]) { await page.evaluate(attempts => { for(const a of attempts) localStorage.setItem('arithmetic:attempt:v1:'+a.id,JSON.stringify(a)) },attempts) }
const cell = (page: Page, pair: string) => page.getByRole('table', { name: 'First-try accuracy by ordered multiplication pair', exact: true }).locator(`[data-pair="${pair}"]`)
test('direct stats load, reload, client navigation and browser history resolve correctly', async ({page}) => {
  await page.goto('/stats')
  await expect(page.getByRole('region',{name:'Statistics',exact:true})).toBeVisible()
  await expect(page.getByRole('link',{name:'Stats',exact:true})).toHaveAttribute('aria-current','page')
  await expect(page.getByRole('table', { name: 'First-try accuracy by ordered multiplication pair', exact: true }).locator('.stats-cell')).toHaveCount(144)
  await expect(cell(page,'9x6')).toHaveAccessibleName('9 × 6: unattempted (0 questions)')
  await expect(page.getByRole('button',{name:'Start',exact:true})).toBeHidden()
  await page.reload(); await expect(page.getByRole('table', { name: 'First-try accuracy by ordered multiplication pair', exact: true }).locator('.stats-cell')).toHaveCount(144)
  await page.getByRole('link',{name:'Practice',exact:true}).click()
  await expect(page).toHaveURL(/\/$/); await expect(page.getByRole('button',{name:'Start',exact:true})).toBeVisible()
  await page.goBack(); await expect(page.getByRole('region',{name:'Statistics',exact:true})).toBeVisible()
  await page.goForward(); await expect(page.getByRole('button',{name:'Start',exact:true})).toBeVisible()
})
test('correction does not erase first-answer errors, ordered pairs and empty cells remain distinct', async ({page}) => {
  await page.goto('/stats')
  await seed(page,[fixture(),fixture({answer:54,correct:true,elapsedMs:3000,id:crypto.randomUUID(),submittedAt:'2026-01-01T00:00:02.000Z'}),fixture({questionIndex:1,left:6,right:9,answer:54,correct:true,elapsedMs:500,id:crypto.randomUUID(),submittedAt:'2026-01-01T00:00:03.000Z'})])
  await page.reload()
  await expect(cell(page,'9x6')).toHaveText('0%'); await expect(cell(page,'6x9')).toHaveText('100%'); await expect(cell(page,'1x1')).toHaveText('—')
  await expect(cell(page,'9x6')).toHaveAccessibleName(/0% first-try correct \(0 of 1 questions\); 1 wrong submission; average first answer 1.00 s; average solve 3.00 s/)
  expect(await cell(page,'9x6').evaluate(e => getComputedStyle(e).backgroundColor)).not.toEqual(await cell(page,'1x1').evaluate(e => getComputedStyle(e).backgroundColor))
  await cell(page,'9x6').focus(); await expect(page.getByRole('region',{name:'9 × 6 details'})).toBeVisible()
  await page.keyboard.press('ArrowRight'); await expect(cell(page,'9x7')).toBeFocused()
})
test('practice stays mounted while Stats pauses time and disables practice keys', async ({page}) => {
  await page.addInitScript(() => { (window as any).now=0; performance.now=()=> (window as any).now; Object.defineProperty(document,'hasFocus',{value:()=>true}) })
  await page.goto('/'); await page.evaluate(() => {(window as any).now=1000})
  await page.keyboard.press('Enter')
  const input=page.getByRole('textbox',{name:'Answer'})
  const question=await page.getByTestId('question').innerText()
  const [left,right]=question.match(/\d+/g)!.map(Number)
  await page.evaluate(() => {(window as any).now=2000}); await input.fill('0'); await input.press('Enter')
  await input.fill(String(left*right))
  await page.evaluate(() => {(window as any).now=2500}); await page.getByRole('link',{name:'Stats',exact:true}).click()
  await page.evaluate(() => {(window as any).now=10000})
  await page.locator('body').click({position:{x:1,y:1}}); await page.keyboard.press('Enter')
  await page.getByRole('link',{name:'Practice',exact:true}).click()
  await expect(input).toHaveValue(String(left*right)); await expect(page.getByTestId('question')).toHaveText(question)
  await page.evaluate(() => {(window as any).now=10500}); await input.press('Enter')
  const attempts = await page.evaluate(() => Object.keys(localStorage).filter(k=>k.startsWith('arithmetic:attempt:')).map(k=>JSON.parse(localStorage.getItem(k)!)))
  expect(attempts).toHaveLength(2); expect(attempts.find(a=>a.correct).elapsedMs).toBe(2000)
})
test('navigation refreshes storage and cross-tab events update visible statistics', async ({page,context}) => {
  await page.goto('/'); await seed(page,[fixture()]); await page.getByRole('link',{name:'Stats',exact:true}).click()
  await expect(cell(page,'9x6')).toHaveText('0%')
  const other=await context.newPage(); await other.goto('/stats')
  await seed(other,[fixture({roundId:crypto.randomUUID(),answer:54,correct:true})])
  await expect(cell(page,'9x6')).toHaveText('50%')
  await expect(cell(page,'9x6')).toHaveAccessibleName(/1 of 2 questions/)
})
for(const theme of ['dark','light']) test(`stats ${theme} is readable at mobile width without document overflow`, async ({page}) => {
  await page.setViewportSize({width:375,height:812}); await page.goto('/stats')
  await seed(page,[fixture()]); await page.reload()
  if(theme==='light') await page.getByRole('button',{name:'Switch to light theme'}).click()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await expect(cell(page,'9x6')).toHaveText('0%')
  await page.screenshot({path:`artifacts/stats-mobile-${theme}.png`,fullPage:true})
})
